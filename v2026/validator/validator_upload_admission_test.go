// The public constructor starts its real owned loop. Shutdown interrupts the
// actual EVM read and joins it; no supplied historical-verdict callback exists.
func TestValidatorUploadAdmissionCloseJoinsActualRefresh(t *testing.T) {
	t.Parallel()
	fixture := newValidatorUploadAuthorityTestFixture(t)
	entered, left := make(chan struct{}), make(chan struct{})
	fixture.beforeCode = func(ctx context.Context) error { close(entered); defer close(left); <-ctx.Done(); return ctx.Err() }
	owner, err := NewValidatorUploadAdmission(t.Context(), fixture.chain, fixture.native.chain, fixture.config())
	if err != nil {
		t.Fatal(err)
	}
	defer owner.Close()
	<-entered
	owner.Close()
	<-left
	if owner.ctx.Err() == nil || len(owner.entries) != 0 {
		t.Fatal("closed cache retained a refresh owner or entry")
	}
	if err := owner.WaitReady(t.Context()); err == nil {
		t.Fatal("closed refresh owner reported readiness")
	}
}

